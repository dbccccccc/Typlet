export function featureFormulas() {
  return [
    ...inline.map(([id, src]) => ({ id, src, display: false })),
    ...both.flatMap(([id, src]) => [
      { id: `${id}-inline`, src, display: false },
      { id: `${id}-block`, src, display: true },
    ]),
  ];
}
