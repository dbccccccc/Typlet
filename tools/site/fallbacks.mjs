// Generates docs/fallbacks.md, what Typlet draws as MathML or refuses, and
// why, from the test corpus: the formulas Typst renders (test/corpus/*.jsonl,
// with their frames in test/fixtures/), rendered with the source as the
// tests see it.
//
//   node tools/site/fallbacks.mjs [--check]
//
// With --check, fails if docs/fallbacks.md is stale.

import { readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '../..');
const bundle = join(tmpdir(), `typlet-fallbacks-${process.pid}.mjs`);
await build({
  stdin: {
    contents: `export { renderToResult, TypletError, typstVersion } from './src/index.ts';`,
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: bundle,
  logLevel: 'error',
});
const T = await import(pathToFileURL(bundle).href);
rmSync(bundle, { force: true });

const readJsonl = (path) =>
  readFileSync(path, 'utf8')
    .split('\n')
    .filter((line) => line.trim() !== '')
    .map((line) => JSON.parse(line));

// The corpus files of formulas Typst lays out, whose frames test/layout.test.ts compares.
const NAMES = ['paired', 'typst-docs', 'symbols', 'code', 'features', 'levels'];

const counts = { typst: 0, html: 0, mathml: 0, refused: 0, failed: 0 };
/** Reasons by message, with quoted text generalized, and the formulas they apply to. */
const reasons = { mathml: new Map(), refused: new Map(), failed: new Map() };
/** The characters the math font lacks, from the warnings. */
const characters = new Set();
const generalize = (message) => message.replace(/; drawn as MathML$/, '').replace(/"[^"]*"/g, '"…"');
const note = (group, message, formula) => {
  const key = generalize(message);
  const entry = reasons[group].get(key) ?? { count: 0, examples: [] };
  entry.count++;
  if (entry.examples.length < 3) entry.examples.push(formula);
  reasons[group].set(key, entry);
};

for (const name of NAMES) {
  const fixtures = new Map(readJsonl(join(root, `test/fixtures/typst-${T.typstVersion}/${name}.jsonl`)).map((r) => [r.id, r]));
  for (const formula of readJsonl(join(root, `test/corpus/${name}.jsonl`))) {
    if (!fixtures.get(formula.id)?.frame) continue;
    counts.typst++;
    try {
      const result = T.renderToResult(formula.src, { displayMode: formula.display, preamble: formula.preamble, strict: 'ignore' });
      if (result.drawnAs === 'html') {
        counts.html++;
        continue;
      }
      counts.mathml++;
      const fallbacks = result.warnings.filter((warning) => warning.kind === 'fallback');
      if (fallbacks.length === 0) note('mathml', 'drawn as MathML without a warning', formula);
      for (const warning of fallbacks) {
        note('mathml', warning.message, formula);
        // The message quotes the text as JSON.
        const glyph = /^Typlet does not support ("(?:[^"\\]|\\.)*") in HTML output, as New Computer Modern Math has no glyph/.exec(warning.message);
        if (glyph) characters.add(JSON.parse(glyph[1]));
      }
    } catch (e) {
      if (!(e instanceof T.TypletError)) throw e;
      const group = e.kind === 'unsupported' ? 'refused' : 'failed';
      counts[group]++;
      note(group, e.message, formula);
    }
  }
}

const number = (n) => n.toLocaleString('en-US');
const cell = (text) => text.replace(/\|/g, '\\|');
/** A formula with its preamble as a code span on one line, or its id when the source has a backtick. */
const example = ({ id, src, preamble }) => {
  const line = `${preamble ? `${preamble} ` : ''}${src}`.replace(/\r?\n/g, ' ⏎ ').replace(/\s+/g, ' ').trim();
  const shown = line.length > 48 ? `${line.slice(0, 47)}…` : line;
  return `\`${cell(shown.includes('`') ? id : shown)}\``;
};
/** A character, or the code point of a control character. */
const shownCharacter = (c) => {
  const cp = c.codePointAt(0);
  return cp < 0x20 || (cp >= 0x7f && cp <= 0xa0) ? `U+${cp.toString(16).toUpperCase().padStart(4, '0')}` : c;
};
const table = (map) => [
  '| Reason | Formulas | Examples |',
  '|---|---|---|',
  ...[...map.entries()]
    .sort(([a, x], [b, y]) => y.count - x.count || a.localeCompare(b))
    .map(([reason, { count, examples }]) => `| ${cell(reason)} | ${number(count)} | ${examples.map(example).join(', ')} |`),
];
const sorted = [...characters]
  .sort((a, b) => a.codePointAt(0) - b.codePointAt(0))
  .map(shownCharacter)
  .join(' ');
const fence = '`'.repeat(Math.max(0, ...[...sorted.matchAll(/`+/g)].map((m) => m[0].length)) + 1);

const lines = [
  '<!-- Generated by tools/site/fallbacks.mjs from the test corpus. Do not edit by hand. -->',
  '',
  '# What falls back, and why',
  '',
  `Of the ${number(counts.typst)} formulas of the test corpus that Typst ${T.typstVersion} renders, Typlet lays out ${number(counts.html)} as HTML, draws ${number(counts.mathml)} as MathML with a warning, and refuses ${number(counts.refused)}. The corpus (test/corpus/README.md) holds the examples of Typst's documentation, the formulas of TypstPad's symbol picker, a formula for each symbol of the \`sym\` module, and the test cases of Typlet's features and embedded code, so symbols weigh heavily in it. This page is generated from it by tools/site/fallbacks.mjs.`,
  '',
  '## Drawn as MathML',
  '',
  "The `htmlAndMathml` and `html` outputs draw a formula as MathML, which the browser lays out, when Typlet's layout can't draw something in it. The warning, of kind `fallback`, says what, and `renderToResult` returns it with `drawnAs: 'mathml'`.",
  '',
  ...table(reasons.mathml),
  '',
  `The characters New Computer Modern Math has no glyph for, in the corpus: ${fence} ${sorted} ${fence}.`,
  '',
  '## Refused',
  '',
  "A formula with code Typlet doesn't evaluate throws a `TypletError` of kind `unsupported`, which the `fallback` option can render another way, for example with Typst compiled to WebAssembly.",
  '',
  ...table(reasons.refused),
  '',
];
if (counts.failed > 0) {
  lines.push('## Failed', '', 'Formulas Typst renders that Typlet fails on, which are bugs:', '', ...table(reasons.failed), '');
}
const markdown = lines.join('\n');
const target = join(root, 'docs/fallbacks.md');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {}
  if (current !== markdown) {
    console.error('docs/fallbacks.md is stale: run `npm run docs:fallbacks`');
    process.exit(1);
  }
  console.log('docs/fallbacks.md is up to date.');
} else {
  writeFileSync(target, markdown);
  console.log(`Wrote docs/fallbacks.md: ${number(counts.typst)} formulas, ${number(counts.html)} laid out, ${number(counts.mathml)} as MathML, ${number(counts.refused)} refused, ${number(counts.failed)} failed.`);
}
